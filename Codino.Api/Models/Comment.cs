using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace Codino.Api.Models
{
    public class Comment
    {
        // =========================================================
        // ID
        // =========================================================

        [Key]
        public int Id { get; set; }


        // =========================================================
        // USER ID
        // =========================================================
        // شناسه کاربری که این نظر را ثبت کرده است.
        // هر نظر باید حتماً متعلق به یک کاربر باشد.
        // =========================================================

        [Required]
        public int UserId { get; set; }


        // =========================================================
        // COMMENT TEXT
        // =========================================================
        // متن نظر:
        // - اجباری
        // - حداقل ۱ کاراکتر
        // - حداکثر ۵۰۰ کاراکتر
        //
        // محدودیت nvarchar(500) در دیتابیس نیز
        // توسط CodinoDbContext اعمال می‌شود.
        // =========================================================

        [Required(
            ErrorMessage = "متن نظر الزامی است.")]
        [StringLength(
            500,
            MinimumLength = 1,
            ErrorMessage =
                "متن نظر باید بین ۱ تا ۵۰۰ کاراکتر باشد.")]
        [Column(TypeName = "nvarchar(500)")]
        public string Text { get; set; } = string.Empty;


        // =========================================================
        // RATING
        // =========================================================
        // امتیاز نظر باید بین ۱ تا ۵ باشد.
        // =========================================================

        [Range(
            1,
            5,
            ErrorMessage =
                "امتیاز باید بین ۱ تا ۵ باشد.")]
        public int Rating { get; set; }


        // =========================================================
        // CREATED AT
        // =========================================================
        // زمان ثبت نظر.
        // در Controller با DateTime.UtcNow مقداردهی می‌شود.
        // =========================================================

        [Required]
        public DateTime CreatedAt { get; set; }


        // =========================================================
        // APPROVAL
        // =========================================================
        // اگر true باشد، نظر اجازه نمایش عمومی دارد.
        // =========================================================

        public bool IsApproved { get; set; } = false;


        // =========================================================
        // USER NAVIGATION
        // =========================================================
        // ارتباط Comment با User
        // =========================================================

        [ForeignKey(nameof(UserId))]
        public User? User { get; set; }
    }
}